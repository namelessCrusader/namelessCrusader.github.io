"""Learn Stochastic WFC neighbour counts from VGLC Super Mario Bros. levels.

Writes swfc_model.js, which the site loads to generate the footer level.

Usage:
    python3 tools/learn_swfc.py <levels> [--exclude mario-1-2,mario-4-2]

<levels> is either a folder of VGLC .txt levels
(TheVGLC/Super Mario Bros/Processed/) or the processed_levels.pkl
from github.com/namelessCrusader/Stochastic-Wave-Function-Collapse.
"""

import json
import os
import pickle
import sys
from collections import Counter

# Directions in screen coordinates: (dx, dy), with y growing downwards.
DIRECTIONS = {"left": (-1, 0), "right": (1, 0), "up": (0, -1), "down": (0, 1)}


def load_levels(path, exclude=()):
    if path.endswith(".pkl"):
        with open(path, "rb") as f:
            levels = pickle.load(f)
    else:
        levels = {}
        for name in sorted(os.listdir(path)):
            if name.endswith(".txt"):
                with open(os.path.join(path, name)) as f:
                    levels[name[:-4]] = f.read().splitlines()
    return {name: level for name, level in sorted(levels.items()) if name not in exclude}


def learn(levels):
    freq = Counter()
    counts = {}  # counts[tile][direction][neighbour] = how often neighbour sits in that direction
    row_freq = [Counter() for _ in levels[0]]  # row_freq[y][tile]: how often a tile appears at height y
    floor = {}  # floor[a][b]: how often b follows a along the bottom row
    for level in levels:
        height, width = len(level), len(level[0])
        bottom = level[-1]
        for a, b in zip(bottom, bottom[1:]):
            floor.setdefault(a, Counter())[b] += 1
        for y in range(height):
            for x in range(width):
                tile = level[y][x]
                freq[tile] += 1
                row_freq[y][tile] += 1
                per_dir = counts.setdefault(tile, {d: Counter() for d in DIRECTIONS})
                for d, (dx, dy) in DIRECTIONS.items():
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < width and 0 <= ny < height:
                        per_dir[d][level[ny][nx]] += 1
    return {
        "height": len(levels[0]),
        "freq": dict(freq.most_common()),
        "rowFreq": [dict(c) for c in row_freq],
        "floor": {a: dict(c) for a, c in floor.items()},
        "counts": {t: {d: dict(c) for d, c in dirs.items()} for t, dirs in sorted(counts.items())},
    }


def main():
    args = sys.argv[1:]
    exclude = set()
    if "--exclude" in args:
        i = args.index("--exclude")
        exclude = set(args[i + 1].split(","))
        del args[i : i + 2]
    if len(args) != 1:
        sys.exit(__doc__)
    levels = load_levels(args[0], exclude)
    model = learn(list(levels.values()))
    model["levels"] = list(levels)
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "swfc_model.js")
    with open(out, "w") as f:
        f.write("// Generated by tools/learn_swfc.py from VGLC Super Mario Bros. levels. Do not edit by hand.\n")
        f.write("const SWFC_MODEL = " + json.dumps(model, separators=(",", ":")) + ";\n")
    print(f"Learned {len(model['freq'])} tiles from {len(levels)} levels -> {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
